export const pinnedCountry = 'BR'

export interface Country {
  code: string
  name: string
}

export function flagEmoji(code: string) {
  return String.fromCodePoint(...[...code].map((letter) => 0x1f1a5 + letter.charCodeAt(0)))
}

export function flagUrl(code: string) {
  return `https://flagcdn.com/${code.toLowerCase()}.svg`
}

function normalize(value: string) {
  return value
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
}

export function countryList(locale: string): Country[] {
  const names = new Intl.DisplayNames([locale], { type: 'region' })
  const countries = countryCodes.map((code) => ({ code, name: names.of(code) ?? code }))
  const pinned = countries.filter((country) => country.code === pinnedCountry)
  const rest = countries
    .filter((country) => country.code !== pinnedCountry)
    .sort((a, b) => a.name.localeCompare(b.name, locale))
  return [...pinned, ...rest]
}

export function filterCountries(countries: Country[], query: string) {
  const term = normalize(query.trim())
  if (!term) return countries
  return countries.filter((country) => normalize(country.name).includes(term))
}
